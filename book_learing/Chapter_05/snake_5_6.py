age = int(input ('How old are you?'))
if age <2:
    print('It is a baby')
elif age <4:
    print('It is a infant')
elif age <13:
    print('It is a Children')
elif age <18:
    print('It is a Young man')
elif age <65:
    print('It is a adult')
elif age >=65:
    print('It is a old man')
